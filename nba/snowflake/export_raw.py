"""Export the NBA raw tables for Snowflake, and write the SQL that loads them.

    work/nba/.venv/bin/python -I nba/snowflake/export_raw.py

Reads work/nba/source/nba_analysis.duckdb (read-only) and writes:
  work/nba/snowflake/parquet/<table>.parquet   one file per RAW table
  nba/snowflake/raw_tables.sql                 CREATE TABLE + COPY INTO, one per table

Only the six RAW tables are loaded: dbt builds every other table on Snowflake
(make_dbt_parity.py), as a Snowflake customer's own dbt project would. Tables
keep their DuckDB names (RAW.RAW_GAMES ...) and plain, unquoted column names,
so the benchmark's gold SQL (`FROM RAW.raw_teams`, lower-case columns) resolves
on Snowflake exactly as it does on DuckDB. Never INFER_SCHEMA: it keeps
lower-case names quoted, and every gold query would fail.
"""
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "work" / "nba" / "source" / "nba_analysis.duckdb"
OUT = ROOT / "work" / "nba" / "snowflake" / "parquet"
SQL = Path(__file__).resolve().parent / "raw_tables.sql"

# DuckDB type -> Snowflake type. Integers become NUMBER(38,0); DOUBLE becomes FLOAT.
TYPES = {
    "BIGINT": "NUMBER(38,0)", "INTEGER": "NUMBER(38,0)", "SMALLINT": "NUMBER(38,0)", "TINYINT": "NUMBER(38,0)",
    "HUGEINT": "NUMBER(38,0)", "UBIGINT": "NUMBER(38,0)", "UINTEGER": "NUMBER(38,0)",
    "DOUBLE": "FLOAT", "FLOAT": "FLOAT", "REAL": "FLOAT",
    "VARCHAR": "VARCHAR", "BOOLEAN": "BOOLEAN", "DATE": "DATE",
    "TIMESTAMP": "TIMESTAMP_NTZ", "TIMESTAMP WITH TIME ZONE": "TIMESTAMP_TZ",
}


def snowflake_type(duck: str) -> str:
    if duck.startswith("DECIMAL"):
        return duck.replace("DECIMAL", "NUMBER")
    if duck not in TYPES:
        raise SystemExit(f"no Snowflake type for DuckDB type {duck}")
    return TYPES[duck]


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    con = duckdb.connect(str(SOURCE), read_only=True)
    tables = [row[0] for row in con.execute(
        "SELECT table_name FROM duckdb_tables() WHERE schema_name = 'RAW' ORDER BY table_name").fetchall()]
    lines = [
        "-- Generated by nba/snowflake/export_raw.py from the NBA DuckDB file. Run as ZLENS_BENCH_LOADER",
        "-- after setup.sql and after load.py has PUT the Parquet files on @NBA.RAW.NBA_STAGE.",
        "USE ROLE ZLENS_BENCH_LOADER;",
        "USE WAREHOUSE ZLENS_BENCH_WH;",
        "USE SCHEMA NBA.RAW;",
        "",
    ]
    total = 0
    for table in tables:
        columns = con.execute(
            "SELECT column_name, data_type FROM duckdb_columns() WHERE schema_name = 'RAW' AND table_name = ? ORDER BY column_index",
            [table]).fetchall()
        rows = con.execute(f'SELECT count(*) FROM "RAW"."{table}"').fetchone()[0]
        total += rows
        path = OUT / f"{table}.parquet"
        con.execute(f"COPY (SELECT * FROM \"RAW\".\"{table}\") TO '{path}' (FORMAT parquet, COMPRESSION zstd)")
        for name, _ in columns:
            if not name.replace("_", "").isalnum() or name[0].isdigit():
                raise SystemExit(f"{table}.{name} needs quoting on Snowflake; rename it first")
        body = ",\n".join(f"    {name.upper()} {snowflake_type(dtype)}" for name, dtype in columns)
        lines += [
            f"-- {table}: {rows:,} rows",
            f"CREATE OR REPLACE TABLE {table.upper()} (\n{body}\n);",
            f"COPY INTO {table.upper()} FROM @NBA_STAGE/{table}.parquet",
            "    FILE_FORMAT = (FORMAT_NAME = NBA_PARQUET) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = ABORT_STATEMENT;",
            f"SELECT '{table}' AS table_name, COUNT(*) = {rows} AS loaded_all FROM {table.upper()};",
            "",
        ]
        print(f"{table}: {rows:,} rows, {len(columns)} columns -> {path.relative_to(ROOT)} ({path.stat().st_size / 1e6:.1f} MB)")
    SQL.write_text("\n".join(lines))
    print(f"{len(tables)} tables, {total:,} rows; load SQL -> {SQL.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
