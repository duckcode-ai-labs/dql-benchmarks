-- ZLens benchmark: the NBA data on Snowflake. Run once, as ACCOUNTADMIN, in a Snowsight worksheet.
-- Paste the two public keys first (nba/snowflake/README.md, step 2: no passwords anywhere).
--
-- What it makes, least privilege as an enterprise customer would set it up:
--   ZLENS_BENCH_WH      X-Small warehouse, auto-suspends after 60 s, 10-minute statement limit
--   ZLENS_BENCH_RM      resource monitor: notify at 75%, suspend at 100% of 25 credits a month
--   NBA                 database: RAW (loaded), TRANSFORMED (dbt), DEV (dbt snapshots)
--   ZLENS_BENCH_LOADER  role that loads RAW and runs dbt; owns NBA
--   ZLENS_READER        read-only role ZLens connects with (SELECT on NBA, the warehouse)
--   ZLENS_BENCH_SVC     service user (key pair) for loading and dbt
--   ZLENS_APP_SVC       service user (key pair) ZLens and the grader use: ZLENS_READER only

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS ZLENS_READER COMMENT = 'ZLens: read-only access to the benchmark data';
CREATE ROLE IF NOT EXISTS ZLENS_BENCH_LOADER COMMENT = 'ZLens benchmark: loads RAW and runs dbt';
GRANT ROLE ZLENS_READER TO ROLE ZLENS_BENCH_LOADER;
GRANT ROLE ZLENS_BENCH_LOADER TO ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS ZLENS_BENCH_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 600
  COMMENT = 'ZLens benchmark and live tests';
CREATE RESOURCE MONITOR IF NOT EXISTS ZLENS_BENCH_RM WITH CREDIT_QUOTA = 25 FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY TRIGGERS ON 75 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE ZLENS_BENCH_WH SET RESOURCE_MONITOR = ZLENS_BENCH_RM;
GRANT USAGE ON WAREHOUSE ZLENS_BENCH_WH TO ROLE ZLENS_READER;
GRANT OPERATE ON WAREHOUSE ZLENS_BENCH_WH TO ROLE ZLENS_BENCH_LOADER;

CREATE DATABASE IF NOT EXISTS NBA COMMENT = 'NBA benchmark data (dql-benchmarks nba/snowflake)';
CREATE SCHEMA IF NOT EXISTS NBA.RAW;
CREATE SCHEMA IF NOT EXISTS NBA.TRANSFORMED;
CREATE SCHEMA IF NOT EXISTS NBA.DEV;
GRANT OWNERSHIP ON SCHEMA NBA.RAW TO ROLE ZLENS_BENCH_LOADER REVOKE CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA NBA.TRANSFORMED TO ROLE ZLENS_BENCH_LOADER REVOKE CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA NBA.DEV TO ROLE ZLENS_BENCH_LOADER REVOKE CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE NBA TO ROLE ZLENS_BENCH_LOADER REVOKE CURRENT GRANTS;

-- ZLens reads everything in NBA, now and later (dbt rebuilds tables and views).
GRANT USAGE ON DATABASE NBA TO ROLE ZLENS_READER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE NBA TO ROLE ZLENS_READER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE NBA TO ROLE ZLENS_READER;
GRANT SELECT ON ALL TABLES IN DATABASE NBA TO ROLE ZLENS_READER;
GRANT SELECT ON FUTURE TABLES IN DATABASE NBA TO ROLE ZLENS_READER;
GRANT SELECT ON ALL VIEWS IN DATABASE NBA TO ROLE ZLENS_READER;
GRANT SELECT ON FUTURE VIEWS IN DATABASE NBA TO ROLE ZLENS_READER;

-- Service users: key pair only (Snowflake is retiring single-factor passwords).
CREATE USER IF NOT EXISTS ZLENS_BENCH_SVC TYPE = SERVICE
  DEFAULT_ROLE = ZLENS_BENCH_LOADER DEFAULT_WAREHOUSE = ZLENS_BENCH_WH
  RSA_PUBLIC_KEY = '<paste the body of ~/.zlens-bench/snowflake/loader.pub, without the BEGIN/END lines>';
GRANT ROLE ZLENS_BENCH_LOADER TO USER ZLENS_BENCH_SVC;
CREATE USER IF NOT EXISTS ZLENS_APP_SVC TYPE = SERVICE
  DEFAULT_ROLE = ZLENS_READER DEFAULT_WAREHOUSE = ZLENS_BENCH_WH
  RSA_PUBLIC_KEY = '<paste the body of ~/.zlens-bench/snowflake/reader.pub, without the BEGIN/END lines>';
GRANT ROLE ZLENS_READER TO USER ZLENS_APP_SVC;

-- The stage and file format the loader uses.
USE ROLE ZLENS_BENCH_LOADER;
CREATE FILE FORMAT IF NOT EXISTS NBA.RAW.NBA_PARQUET TYPE = PARQUET;
CREATE STAGE IF NOT EXISTS NBA.RAW.NBA_STAGE FILE_FORMAT = NBA.RAW.NBA_PARQUET;

